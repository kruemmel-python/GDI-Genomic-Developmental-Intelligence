#include "gpi/prompt_program_synthesizer.hpp"

#include <algorithm>
#include <limits>
#include <sstream>
#include <string_view>
#include <unordered_set>

namespace genomic::gpi {
namespace {

bool has(const PromptResolution& resolution, std::string_view operation) {
    return std::any_of(resolution.capabilities.begin(), resolution.capabilities.end(),
                       [operation](const ActivatedCapability& capability) {
                           return capability.operation == operation;
                       });
}

std::string predicate(ThresholdMode mode, int64_t threshold) {
    std::string op;
    switch (mode) {
        case ThresholdMode::Greater: op = ">"; break;
        case ThresholdMode::GreaterEqual: op = ">="; break;
        case ThresholdMode::Less: op = "<"; break;
        case ThresholdMode::LessEqual: op = "<="; break;
        case ThresholdMode::None: return "true";
    }
    const std::string literal = threshold == std::numeric_limits<int64_t>::min()
        ? "(-9223372036854775807LL - 1LL)"
        : std::to_string(threshold) + "LL";
    return "sample " + op + " " + literal;
}

} // namespace

PromptProgramArtifact PromptProgramSynthesizer::synthesize(const PromptResolution& resolution) {
    PromptProgramArtifact result;
    result.genomeHash = resolution.genomeHash;
    if (!resolution.supported) {
        result.diagnostics = resolution.diagnostics;
        if (result.diagnostics.empty()) result.diagnostics.push_back("Prompt was not validated");
        return result;
    }
    if (!has(resolution, "input")) {
        result.diagnostics.push_back("No activated genomic input capability");
        return result;
    }
    const bool csv = has(resolution, "csv");
    const bool alarm = has(resolution, "alarm");
    const bool mean = has(resolution, "mean");
    const bool max = has(resolution, "max");
    const bool min = has(resolution, "min");
    const bool sum = has(resolution, "sum");
    const bool count = has(resolution, "count");
    if (alarm && !resolution.threshold) {
        result.diagnostics.push_back("Alarm requires a numeric threshold");
        return result;
    }
    std::unordered_set<std::string> operations;
    for (const auto& capability : resolution.capabilities) {
        if (!resolution.regulation.activeRegions.contains(capability.regionId) ||
            !operations.insert(capability.operation).second) {
            result.diagnostics.push_back("Invalid or duplicate activated genomic capability: " + capability.id);
            return result;
        }
        result.plan.push_back("Activate " + capability.operation + " from genome region " +
                              std::to_string(capability.regionId) + " via molecule " +
                              std::to_string(capability.moleculeSignature));
    }
    if (resolution.expectedSamples)
        result.plan.push_back("Read exactly " + std::to_string(*resolution.expectedSamples) + " numeric samples");
    else
        result.plan.push_back("Read numeric samples from stdin until EOF");
    if (resolution.threshold)
        result.plan.push_back("Apply threshold " + std::to_string(*resolution.threshold));

    std::ostringstream source;
    source << "// Generated by GPI genomic capability synthesis v1.\n"
           << "// Genome hash: " << resolution.genomeHash << "\n"
           << "// Only explicitly activated genomic operations are emitted.\n"
           << "#include <cstddef>\n#include <cstdint>\n#include <iostream>\n";
    if (csv) source << "#include <fstream>\n";
    if (mean) source << "#include <iomanip>\n";
    source << "\nint main() {\n"
           << "    std::int64_t sample = 0;\n"
           << "    std::size_t seen = 0;\n";
    if (mean || sum) source << "    long double total = 0.0L;\n";
    if (max) source << "    std::int64_t maximum = 0;\n";
    if (min) source << "    std::int64_t minimum = 0;\n";
    if (count) source << "    std::size_t selected = 0;\n";
    if (alarm) source << "    std::size_t alarms = 0;\n";
    if (csv) {
        source << "    std::ofstream csv(\"gpi_measurements.csv\", std::ios::trunc);\n"
               << "    if (!csv) { std::cerr << \"CSV_OPEN_ERROR\\n\"; return 2; }\n"
               << "    csv << \"index,value\\n\";\n";
    }
    source << "    while (";
    if (resolution.expectedSamples) source << "seen < " << *resolution.expectedSamples << " && ";
    source << "(std::cin >> sample)) {\n"
           << "        ++seen;\n";
    if (mean || sum) source << "        total += static_cast<long double>(sample);\n";
    if (max) source << "        if (seen == 1 || sample > maximum) maximum = sample;\n";
    if (min) source << "        if (seen == 1 || sample < minimum) minimum = sample;\n";
    if (count) {
        source << "        if (" << (resolution.threshold ? predicate(resolution.thresholdMode, *resolution.threshold) : "true")
               << ") ++selected;\n";
    }
    if (alarm) {
        source << "        if (" << predicate(resolution.thresholdMode, *resolution.threshold) << ") {\n"
               << "            ++alarms;\n"
               << "            std::cout << \"ALARM sensor=\" << seen << \" value=\" << sample << '\\n';\n"
               << "        }\n";
    }
    if (csv) source << "        csv << seen << ',' << sample << '\\n';\n";
    source << "    }\n";
    if (resolution.expectedSamples) {
        source << "    if (seen != " << *resolution.expectedSamples
               << ") { std::cerr << \"INSUFFICIENT_SAMPLES\\n\"; return 3; }\n";
    }
    source << "    if (!std::cin.eof() && std::cin.fail()) {\n"
           << "        std::cerr << \"INVALID_INPUT\\n\"; return 4;\n"
           << "    }\n"
           << "    if (seen == 0) { std::cerr << \"NO_SAMPLES\\n\"; return 3; }\n";
    if (csv) {
        source << "    csv.flush();\n"
               << "    if (!csv.good()) { std::cerr << \"CSV_WRITE_ERROR\\n\"; return 5; }\n";
    }
    source << "    std::cout << \"SAMPLES=\" << seen << '\\n';\n";
    if (sum) source << "    std::cout << \"SUM=\" << total << '\\n';\n";
    if (mean) source << "    std::cout << \"MEAN=\" << std::fixed << std::setprecision(2) "
                     "<< (total / static_cast<long double>(seen)) << '\\n';\n";
    if (max) source << "    std::cout << \"MAX=\" << maximum << '\\n';\n";
    if (min) source << "    std::cout << \"MIN=\" << minimum << '\\n';\n";
    if (count) source << "    std::cout << \"COUNT=\" << selected << '\\n';\n";
    if (alarm) source << "    std::cout << \"ALARMS=\" << alarms << '\\n';\n";
    if (csv) source << "    std::cout << \"CSV=gpi_measurements.csv\\n\";\n";
    source << "    return 0;\n}\n";
    result.source = source.str();
    result.generated = true;
    return result;
}

} // namespace genomic::gpi
